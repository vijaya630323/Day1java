 class Narrow {
    public static void main(String[] args) {
        double dou=10.2345;
        int val=(int)dou;
        System.out.println(dou);
        System.out.println(val);
        int value=50;
        char ch=(char)value;
        System.out.println(value);
        System.out.println(ch);
        float flt=3.14f;
        byte bt=(byte)flt;
        System.out.println(flt);
        System.out.println(bt);
        



        
    }

    
}
